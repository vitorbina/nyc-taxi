#!/usr/bin/env bash
#
# Create the access personas in each tool, with each tool's own access control:
#
#   data_engineer  builds and runs the pipeline
#                  Airflow: op (set in docker-compose.yml, SIMPLE_AUTH_MANAGER_USERS)
#                  Superset: Alpha + sql_lab    MinIO: read/write on the lake bucket only
#   analyst        only consumes the dashboards
#                  Superset: Gamma + nyc_taxi_viewer (the dashboard's datasets only)
#                  no Airflow user, no MinIO user
#
# Passwords come from .env. Idempotent: re-running resets roles and passwords to .env.
# Run after the stack is up and the dashboards are imported (import_dashboards.sh).
#
# Usage:
#   set -a; source .env; set +a
#   ./scripts/create_personas.sh
#
set -euo pipefail

: "${SUPERSET_ENGINEER_PASSWORD:?not set; run: set -a; source .env; set +a}"
: "${SUPERSET_ANALYST_PASSWORD:?not set; run: set -a; source .env; set +a}"
: "${MINIO_ENGINEER_PASSWORD:?not set; run: set -a; source .env; set +a}"
: "${MINIO_BUCKET:?not set; run: set -a; source .env; set +a}"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "==> Superset"
docker exec -i \
    -e SUPERSET_ENGINEER_PASSWORD -e SUPERSET_ANALYST_PASSWORD \
    nyc_superset python - < "$SCRIPT_DIR/../superset/personas.py" 2>/dev/null

echo "==> MinIO"
# Policy: every S3 action, but only on the lake bucket (no admin, no other buckets)
docker exec -i -e MINIO_ENGINEER_PASSWORD -e BUCKET="$MINIO_BUCKET" nyc_minio sh -s <<'EOF'
set -e
mc alias set local http://localhost:9000 "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null
cat > /tmp/lake-readwrite.json <<JSON
{
  "Version": "2012-10-17",
  "Statement": [{
    "Effect": "Allow",
    "Action": ["s3:*"],
    "Resource": ["arn:aws:s3:::$BUCKET", "arn:aws:s3:::$BUCKET/*"]
  }]
}
JSON
mc admin policy create local lake-readwrite /tmp/lake-readwrite.json >/dev/null
mc admin user add local data_engineer "$MINIO_ENGINEER_PASSWORD" >/dev/null
mc admin policy attach local lake-readwrite --user data_engineer >/dev/null 2>&1 || true
rm -f /tmp/lake-readwrite.json
echo "data_engineer: lake-readwrite ($BUCKET)"
EOF

echo "==> Airflow"
echo "data_engineer: op (docker-compose.yml). Password, generated by Airflow on first start:"
echo "    docker exec nyc_airflow_webserver cat /opt/airflow/simple_auth_manager_passwords.json.generated"
